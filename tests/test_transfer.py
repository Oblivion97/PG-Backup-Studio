# ---------------------------------------------------------------- spec checks

def test_parse_spec_refusals():
    with pytest.raises(TransferError, match="same table"):
        spec(target_database=DB_A)
    with pytest.raises(TransferError, match="Type the target table name"):
        spec(existing="replace")
    with pytest.raises(TransferError, match="mapped twice"):
        spec(columns=[{"target": "id", "source": "id"}, {"target": "id", "source": "customer"}])
    with pytest.raises(TransferError, match="Map at least one column"):
        spec(columns=[])
    with pytest.raises(TransferError, match="append, skip or replace"):
        spec(existing="merge")
    assert spec(where="WHERE id > 1").where == "id > 1"
    assert spec(create=True, existing="replace").existing == "append"   # a new table has nothing to replace


def test_plan_refusals(dbs, server):
    def plan(**kw):
        return transfer.preview(server, server, spec(**kw))
    with pytest.raises(TransferError, match="name cannot be empty|cannot be empty"):
        plan(target_schema="public", target_table="clients", columns=[{"target": "label", "source": "note"}])
    with pytest.raises(TransferError, match="no primary key or unique"):
        plan(target_schema="public", target_table="nokey", existing="skip",
             columns=[{"target": "name", "source": "customer"}])
    with pytest.raises(TransferError, match="generated"):
        plan(columns=[{"target": "customer", "source": "customer"}, {"target": "total_x2", "source": "amount"}])
    with pytest.raises(TransferError, match="Source column zz does not exist"):
        plan(columns=[{"target": "customer", "source": "zz"}])
    with pytest.raises(TransferError, match="row filter is not valid"):
        plan(where="no_such_col = 1")
    with pytest.raises(TransferError, match="already exists"):
        plan(create=True)
    with pytest.raises(TransferError, match="choose to create it"):
        plan(target_table="missing_table")


def test_preview_lists_the_sql_and_changes_nothing(dbs, server):
    reset_b("sales.orders")
    r = transfer.preview(server, server, spec(existing="skip"))
    sqls = [s["sql"] for s in r["statements"]]
    assert r["statements"][0]["on"] == "source" and sqls[0].startswith('COPY (SELECT "id", "customer"')
    assert any("CREATE TEMP TABLE" in s for s in sqls) and any("ON CONFLICT DO NOTHING" in s for s in sqls)
    assert any("setval" in s for s in sqls) and r["sequences"] == ["id"] and r["est_rows"] == 3
    assert q(DB_B, "SELECT count(*) FROM sales.orders")[0][0] == 0


