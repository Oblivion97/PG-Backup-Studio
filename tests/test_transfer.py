def test_cancel_mid_copy_leaves_target_unchanged(dbs, server):
    cancel = threading.Event()

    def progress(event, data):
        if event == "table_progress" and data["rows"] > 0:
            cancel.set()
    with pytest.raises(Cancelled):
        transfer.run_transfer(server, server, spec(source={"database": DB_A, "schema": "public", "table": "big"},
                                                   create=True, target_schema="public", target_table="big_copy"),
                              progress=progress, cancel=cancel)
    assert q(DB_B, "SELECT to_regclass('public.big_copy') IS NULL") == [(True,)]


