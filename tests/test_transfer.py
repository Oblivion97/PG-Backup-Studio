def test_skip_existing_and_replace(dbs, server):
    reset_b("sales.orders")
    with connect(DB_B) as c:
        c.execute("INSERT INTO sales.orders (id, customer) VALUES (2, 'kept')")
    res = transfer.run_transfer(server, server, spec(existing="skip"))
    assert (res["rows_read"], res["rows_written"], res["rows_skipped"]) == (3, 2, 1)
    assert q(DB_B, "SELECT customer FROM sales.orders WHERE id = 2") == [("kept",)]
    with pytest.raises(TransferError, match="duplicate key.*skip rows that already exist.*Nothing was changed"):
        transfer.run_transfer(server, server, spec())
    res = transfer.run_transfer(server, server, spec(existing="replace", confirm="orders"))
    assert res["truncated"] and q(DB_B, "SELECT count(*) FROM sales.orders") == [(3,)]
    assert q(DB_B, "SELECT customer FROM sales.orders WHERE id = 2") == [("bob",)]


def test_failure_rolls_back_everything(dbs, server):
    reset_b("public.strict")
    with connect(DB_B) as c:
        c.execute("INSERT INTO public.strict VALUES (99, 'before')")
    bad = [{"target": "id", "source": "id"}, {"target": "must", "source": "note"}]   # bob's note is NULL
    with pytest.raises(TransferError, match=r'null value in column "must".*\(row 2\).*Nothing was changed'):
        transfer.run_transfer(server, server, spec(target_schema="public", target_table="strict", columns=bad,
                                                   existing="replace", confirm="strict"))
    assert q(DB_B, "SELECT * FROM public.strict") == [(99, "before")]   # TRUNCATE rolled back too
    with pytest.raises(TransferError, match="invalid input syntax for type integer"):
        transfer.run_transfer(server, server, spec(target_schema="public", target_table="strict",
                                                   columns=[{"target": "id", "source": "customer"}, {"target": "must", "source": "customer"}]))
    with pytest.raises(TransferError):   # create + bad conversion: the new table is not left behind
        transfer.run_transfer(server, server, spec(create=True, target_schema="tmp_fail", target_table="t",
                                                   where="customer = 'nobody' OR 1/0 = 1"))
    assert q(DB_B, "SELECT count(*) FROM pg_namespace WHERE nspname = 'tmp_fail'") == [(0,)]


