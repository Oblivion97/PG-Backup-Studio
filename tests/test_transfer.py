JOIN_QUERY = """
-- orders with a running count, two tables joined
WITH o AS (SELECT id, customer, amount FROM sales.orders)
SELECT o.id, o.customer AS name, o.amount::text AS amount_text, b.v AS label
FROM o JOIN public.big b ON b.id = o.id   -- trailing comment
ORDER BY o.id;
"""


def qspec(**kw):
    data = {"source": {"database": DB_A, "query": JOIN_QUERY},
            "target": {"server_id": "local", "database": DB_B, "schema": "public", "table": "clients"},
            "columns": [{"target": "name", "source": "name"}, {"target": "amount_text", "source": "amount_text"},
                        {"target": "label", "source": "label"}]}
    data.update(kw)
    return transfer.parse_spec(data, same_server=True)


def test_clean_query():
    assert transfer.clean_query("  select 1 ;; ") == "select 1"
    assert transfer.clean_query("/* x */ -- y\n(select 1)") == "/* x */ -- y\n(select 1)"
    for bad in ("", "   ", None, "delete from t", "update t set a = 1", "create table x (a int)"):
        with pytest.raises(TransferError):
            transfer.clean_query(bad)


def test_compare_query_result(dbs, server):
    r = transfer.compare(server, DB_A, None, None, server, DB_B, "public", "clients", query=JOIN_QUERY)
    assert r["match"] == "different" and r["source"]["kind"] == "query"
    assert [c["name"] for c in r["source"]["columns"]] == ["id", "name", "amount_text", "label"]
    assert [c["type"] for c in r["source"]["columns"]] == ["integer", "text", "text", "text"]
    m = {x["target"]: x["source"] for x in r["mapping"]}
    assert m["name"] == "name" and m["amount_text"] == "amount_text" and m["label"] == "label" and m["client_id"] is None
    missing = transfer.compare(server, DB_A, None, None, server, DB_B, "public", "report", query="SELECT 1 AS n, 'x'::varchar(5) AS s")
    assert missing["match"] == "missing" and 'CREATE TABLE "public"."report"' in missing["create_sql"][0]
    assert '"s" character varying(5)' in missing["create_sql"][0]


def test_query_errors_are_clear(dbs, server):
    def cmp(q):
        return transfer.compare(server, DB_A, None, None, server, DB_B, "public", "clients", query=q)
    with pytest.raises(TransferError, match="does not run: relation \"nope\" does not exist"):
        cmp("SELECT * FROM nope")
    with pytest.raises(TransferError, match="more than one column named id"):
        cmp("SELECT o.id, b.id FROM sales.orders o JOIN public.big b ON b.id = o.id")
    with pytest.raises(TransferError, match="has no name"):
        cmp("SELECT count(*) + 1 FROM sales.orders")
    with pytest.raises(TransferError, match="returns rows"):
        cmp("DELETE FROM sales.orders")
    with pytest.raises(TransferError, match="does not run"):   # a second statement is a syntax error, nothing runs
        cmp("SELECT 1 AS a; DELETE FROM sales.orders")
    assert q(DB_A, "SELECT count(*) FROM sales.orders") == [(3,)]


