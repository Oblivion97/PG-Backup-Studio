def test_direct_transfer_copies_every_value(dbs, server):
    reset_b("sales.orders")
    events = []
    res = transfer.run_transfer(server, server, spec(), progress=lambda e, d: events.append(e))
    assert res["rows_read"] == res["rows_written"] == 3 and res["rows_skipped"] == 0 and res["sequences"] == ["id"]
    assert q(DB_A, f"SELECT {ORDER_COLS} FROM sales.orders ORDER BY id") == q(DB_B, f"SELECT {ORDER_COLS} FROM sales.orders ORDER BY id")
    assert {"phase", "totals", "table_start", "table_progress"} <= set(events)
    with connect(DB_B) as c:   # the sequence moved past the copied ids
        assert c.execute("INSERT INTO sales.orders (customer) VALUES ('new') RETURNING id").fetchone()[0] == 4


