def q(dbname, query, params=None):
    with connect(dbname) as c:
        return c.execute(query, params).fetchall()


def reset_b(*tables):
    with connect(DB_B) as c:
        for t in tables:
            c.execute(f"TRUNCATE {t} RESTART IDENTITY")


def spec(**kw):
    data = {"source": {"database": DB_A, "schema": "sales", "table": "orders"},
            "target": {"server_id": "local", "database": DB_B, "schema": "sales", "table": "orders"},
            "columns": [{"target": c, "source": c} for c in ("id", "customer", "amount", "note", "tags", "meta", "raw", "placed")]}
    for k, v in kw.items():
        if k in ("where",):
            data["source"]["where"] = v
        elif k.startswith("target_"):
            data["target"][k[7:]] = v
        else:
            data[k] = v
    return transfer.parse_spec(data, same_server=True)


ORDER_COLS = "id, customer, amount, note, tags, meta, raw, placed, total_x2"


