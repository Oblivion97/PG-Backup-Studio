def test_api_compare_preview_and_job(dbs, tmp_path):
    from app import create_app
    from engine.console import ConsoleManager
    from jobs import JobManager
    from store import Store
    s = pg_settings()
    st = Store(tmp_path / "d")
    a = st.save_server({"name": "A", "host": s["host"], "port": s["port"], "user": s["user"], "password": s["password"],
                        "remember_password": True})
    b = st.save_server({"name": "B", "host": s["host"], "port": s["port"], "user": s["user"], "password": s["password"],
                        "remember_password": True})
    mgr = JobManager(st)
    c = create_app(st, mgr, ConsoleManager()).test_client()
    reset_b("sales.orders")
    base = f"/api/servers/{a['id']}/transfer"
    body = {"source": {"database": DB_A, "schema": "sales", "table": "orders"},
            "target": {"server_id": b["id"], "database": DB_B, "schema": "sales", "table": "orders"}}
    r = c.post(base + "/compare", json=body, headers=H)
    assert r.status_code == 200 and r.get_json()["match"] == "identical"
    cols = [{"target": m["target"], "source": m["source"]} for m in r.get_json()["mapping"] if m["source"]]
    full = {**body, "columns": cols, "existing": "append"}
    r = c.post(base + "/preview", json=full, headers=H)
    assert r.status_code == 200 and r.get_json()["est_rows"] == 3
    assert c.post(base + "/preview", json={**full, "existing": "replace"}, headers=H).status_code == 400
    assert c.post(base + "/compare", json={**body, "target": {}}, headers=H).status_code == 400
    r = c.post(base, json=full, headers=H)
    assert r.status_code == 202
    job_id = r.get_json()["job_id"]
    deadline = time.monotonic() + 30
    while (snap := c.get(f"/api/jobs/{job_id}", headers=H).get_json())["status"] == "running" and time.monotonic() < deadline:
        time.sleep(0.1)
    assert snap["status"] == "success", snap
    assert snap["kind"] == "transfer" and snap["result"]["rows_written"] == 3 and snap["percent"] == 100
    assert snap["transfer"]["source"]["table"] == "sales.orders" and snap["transfer"]["target"]["server"] == "B"
    h = st.get_history(job_id)
    assert h["kind"] == "transfer" and h["status"] == "success" and h["rows"] == 3 and h["table"] == "sales.orders"
    assert h["source"]["database"] == DB_A and h["server"]["id"] == b["id"]
    assert any("Transfer finished: 3 rows" in line["msg"] for line in snap["log"])


def test_job_marks_source_database_busy(dbs, tmp_path):
    from jobs import JobManager
    from store import Store
    s = pg_settings()
    st = Store(tmp_path / "d")
    a = st.save_server({"name": "A", "host": s["host"], "port": s["port"], "user": s["user"], "password": s["password"],
                        "remember_password": True})
    b = st.save_server({"name": "B", "host": "other", "user": "u", "remember_password": True})
    release = threading.Event()

    def slow(src, tgt, sp, progress=None, cancel=None):
        release.wait(10)
        return {"rows_read": 0, "rows_written": 0, "rows_skipped": 0, "target": sp.target_label}
    mgr = JobManager(st, transfer_fn=slow)
    job = mgr.start_transfer(a["id"], b["id"], {"source": {"database": DB_A, "schema": "s", "table": "t"},
                                                "target": {"server_id": b["id"], "database": "x", "schema": "s", "table": "t"},
                                                "columns": [{"target": "c", "source": "c"}]})
    assert mgr.jobs_using(a["id"], DB_A) == [job] and mgr.jobs_using(b["id"], "x") == [job]
    assert mgr.jobs_using(a["id"], "x") == []
    release.set()
    mgr._jobs[job].thread.join(5)
    assert mgr.get_job(job)["status"] == "success"
